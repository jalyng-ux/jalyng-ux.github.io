    private void medianButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_medianButtonActionPerformed
   
        // Get the numbers entered
        String[] numbers = statsTextField.getText().split(",");
        double[] data = new double[numbers.length];

        // Convert the numbers
        for (int i = 0; i < numbers.length; i++) {
            data[i] = Double.parseDouble(numbers[i].trim());
        }

        // Sort the numbers
        java.util.Arrays.sort(data);

        // Find the middle number
        int middle = data.length / 2;
        double median;

        if (data.length % 2 == 0) {
            median = (data[middle - 1] + data[middle]) / 2;
        } 
        else {
        median = data[middle];
        }

        // Display the answer
        answerLabel.setText("Median: " + median);

    }//GEN-LAST:event_medianButtonActionPerformed

    private void meanButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_meanButtonActionPerformed
        // Get the numbers entered
        String[] numbers = statsTextField.getText().split(",");

        // Start the total at zero
        double total = 0;

        // Add all the numbers
        for (String number : numbers) {
        total = total + Double.parseDouble(number.trim());
        }

        // Calculate the mean
        double mean = total / numbers.length;

        // Display the answer
        answerLabel.setText("Mean: " + mean);
    }//GEN-LAST:event_meanButtonActionPerformed

