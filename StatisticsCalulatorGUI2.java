    private void modeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_modeButtonActionPerformed
        
        // Get the numbers entered
        String[] numbers = statsTextField.getText().split(",");
        double[] data = new double[numbers.length];

        // Convert the numbers
        for (int i = 0; i < numbers.length; i++) {
            data[i] = Double.parseDouble(numbers[i].trim());
        }

        // Find the most repeated number
        double mode = data[0];
        int highestCount = 0;

        for (int i = 0; i < data.length; i++) {
            int count = 0;

        for (int j = 0; j < data.length; j++) {
            if (data[i] == data[j]) {
                count++;
            }
        }

        if (count > highestCount) {
            highestCount = count;
            mode = data[i];
        }
    }

    // Display the answer
    if (highestCount == 1) {
        answerLabel.setText("No mode");
    } else {
        answerLabel.setText("Mode: " + mode);
    }
    }//GEN-LAST:event_modeButtonActionPerformed

    private void statsLabelActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_statsLabelActionPerformed
        
    // Get the numbers entered
    String[] numbers = statsTextField.getText().split(",");
    double[] data = new double[numbers.length];
    double total = 0;

    // Convert the numbers and add them together
    for (int i = 0; i < numbers.length; i++) {
        data[i] = Double.parseDouble(numbers[i].trim());
        total = total + data[i];
    }

    // Calculate the mean
    double mean = total / data.length;

    // Sort the numbers
    java.util.Arrays.sort(data);

    // Calculate the median
    int middle = data.length / 2;
    double median;

    if (data.length % 2 == 0) {
        median = (data[middle - 1] + data[middle]) / 2;
    }
    else {
        median = data[middle];
    }

    // Calculate the mode
    double mode = data[0];
    int highestCount = 0;

    for (int i = 0; i < data.length; i++) {
        int count = 0;

    for (int j = 0; j < data.length; j++) {
        if (data[i] == data[j]) {
            count++;
        }
    }

    if (count > highestCount) {
        highestCount = count;
        mode = data[i];
    }
}

   
    // Display the answers on separate lines
    String result = "<html>Mean: " + mean + "<br>Median: " + median;

    if (highestCount == 1) {
        result = result + "<br>Mode: None";
    } 
    else {
        result = result + "<br>Mode: " + mode;
    }

    result = result + "</html>";
    answerLabel.setText(result);
    }//GEN-LAST:event_statsLabelActionPerformed

